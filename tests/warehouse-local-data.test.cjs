const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const seed = require('../data/wms-reference-seed.json');
const model = require('../js/floor-plan-reference-model.js');
const window = { dispatchEvent() {} };
const context = vm.createContext({ window, Event: class {}, console });
for (const file of ['warehouse-operations.js', 'warehouse-3d.js', 'warehouse-local-data.js']) {
  vm.runInContext(fs.readFileSync(path.join(root, 'js', file), 'utf8'), context);
}
const api = window.WmsWarehouseLocalData;
const original = JSON.stringify(seed), data = api.convert(seed);
assert.equal(window.wmsWarehouse3D.validateWarehouseData(data).length, 0);
assert.equal(data.racks.length, 4);
assert.equal(data.inventory.length, 560);
assert.equal(data.equipment.length, 9);
assert.equal(data.operationRoutes.length, 3);
assert.equal(data.meta.floorWidth, 38000);
assert.equal(data.meta.floorDepth, 38500);
assert.equal(data.meta.source, 'localReference');
assert.equal(data.meta.documentId, undefined);
assert.equal(JSON.stringify(seed), original);
const edited = model.copy(seed);
const zone = edited.sheets.findIndex(sheet => sheet.name === '구역설정');
edited.sheets[zone] = model.setCell(edited.sheets[zone], 5, 2, '독립 구역');
assert.equal(api.convert(edited).zones[0].name, '독립 구역');
assert.equal(JSON.stringify(seed), original);
const partial = model.copy(seed);
partial.sheets = partial.sheets.filter(sheet => sheet.name !== '설비 마스터');
assert.match(api.convert(partial).meta.equipmentLoadWarning, /설비 마스터/);
partial.sheets = partial.sheets.filter(sheet => sheet.name !== '랙타입 마스터');
assert.throws(() => api.convert(partial), /랙타입 마스터/);
const renderer = fs.readFileSync(path.join(root, 'js/warehouse-3d.js'), 'utf8');
assert.ok(!/https?:\/\/|fetch\(|import\(|loadGoogleSheet/.test(renderer));
const three = {};
vm.runInNewContext(fs.readFileSync(path.join(root, 'vendor/three.js'), 'utf8'), { window: three, console });
assert.equal(three.THREE.REVISION, '185');
console.log('Local 3D data: independent snapshot, reference edits, optional/required sheets, network-free renderer and bundled Three.js passed.');
