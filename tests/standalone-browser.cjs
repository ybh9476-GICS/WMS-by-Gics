const { chromium } = require(process.env.WMS_PLAYWRIGHT || 'playwright');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..'), out = path.join(root, 'output');
const targetUrl = process.env.WMS_TEST_URL || pathToFileURL(path.join(root, 'index.html')).href;
const fileMode = targetUrl.startsWith('file:');
fs.mkdirSync(out, { recursive: true });
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true, offline: fileMode });
  await context.addInitScript(require('./save-picker-harness.cjs'));
  const page = await context.newPage(), errors = [], requests = [], checks = [];
  page.setDefaultTimeout(10000);
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  page.on('request', request => requests.push(request.url()));
  page.on('dialog', dialog => dialog.accept());
  const action = name => page.locator('[data-action="' + name + '"]');
  const field = name => page.locator('[data-field="' + name + '"]');
  const check = text => { checks.push(text); console.log('PASS', text); };
  const download = async (button, name, reference = false) => {
    const before = await page.evaluate(name => { window.pickerTest.nextName = name; return window.pickerTest.saved.length; }, name);
    await button.click();
    await page.waitForFunction(count => window.pickerTest.saved.length === count + 1, before);
    const file = await page.evaluate(() => window.pickerTest.saved.at(-1)), target = path.join(out, name);
    fs.writeFileSync(target, Buffer.from(file.bytes));
    return target;
  };
  try {
    await page.goto(targetUrl);
    await page.locator('.fp-editor[data-editable=true]').waitFor();
    assert.equal(await page.locator('#loginScreen,#sidebar').count(), 0);
    assert.equal(await page.locator('[data-action=viewer3d]').count(), 1);
    assert.equal(await page.title(), 'WMS by Gics');
    check((fileMode ? 'file:// offline' : targetUrl) + ' opens only the editor without login');
    await page.locator('[data-rack-count=bays]').fill('2'); await page.locator('[data-rack-count=bays]').press('Tab');
    await action('undo').click(); assert.equal(await field('w').inputValue(), '2.50');
    await action('redo').click(); assert.equal(await field('w').inputValue(), '5.00');
    await page.reload(); await page.locator('.fp-editor').waitFor();
    await page.locator('.fp-list [data-select=W01]').click();
    assert.equal(await field('w').inputValue(), '5.00');
    check('Rack edits, undo/redo and browser workspace restoration');
    const gics = await download(action('export'), 'roundtrip.gics');
    const drawing = require('../js/floor-plan-model.js').readFile(JSON.parse(fs.readFileSync(gics,'utf8')));
    assert.equal(drawing.objects.find(object => object.id === 'W01').w, 5);
    await page.locator('[data-file]').setInputFiles(gics);
    assert.equal(await page.locator('[data-tab-select]').count(), 2);
    check('.gics picker output and opening it as a separate drawing');
    await action('reloadMaster').click();
    await page.waitForFunction(() => document.querySelector('.fp-notice').textContent.includes('5개를 새로'));
    await action('masterData').click();
    await page.locator('[data-reference-tab="1"]').waitFor();
    assert.equal(await page.locator('[data-reference-tab]').count(), 13);
    await page.getByRole('tab',{name:'랙타입 마스터',exact:true}).click();
    assert.match(await page.locator('[data-reference-grid]').innerText(),/PALLET-4L/);
    check('Rack master refresh loads the independent local reference table');
    const cell = page.locator('[data-reference-row="5"][data-reference-column="2"]');
    await cell.dblclick();
    await page.locator('.fp-reference-cell-input').fill('로컬 기준정보 수정');
    await page.locator('.fp-reference-cell-input').press('Enter');
    await page.waitForFunction(() => document.querySelector('[data-reference-row="5"][data-reference-column="2"]').textContent.includes('로컬 기준정보 수정'));
    const tbl = await download(action('export'), 'reference.tbl', true);
    const book = require('../js/floor-plan-reference-file.js').parseTbl(fs.readFileSync(tbl,'utf8'));
    assert.equal(book.sheets.length,13);
    assert.ok(book.sheets.find(sheet=>sheet.name==='랙타입 마스터').cells.some(([r,c,v])=>r===5&&c===2&&v==='로컬 기준정보 수정'));
    const xlsx = await download(action('excelExport'), 'reference.xlsx', true);
    const ExcelJS=require('../vendor/exceljs.min.js'), workbook=new ExcelJS.Workbook();
    await workbook.xlsx.load(fs.readFileSync(xlsx));
    assert.equal(workbook.worksheets.filter(sheet=>sheet.state==='visible').length,13);
    assert.equal(workbook.getWorksheet('랙타입 마스터').getCell('B5').value,'로컬 기준정보 수정');
    await page.locator('[data-reference-file=xlsx]').setInputFiles(xlsx);
    await page.waitForFunction(() => document.querySelector('[data-reference-status]').textContent.includes('reference.xlsx의 기준정보 13개 시트를 열었습니다.'));
    await page.locator('[data-reference-file=tbl]').setInputFiles(tbl);
    await page.waitForFunction(() => document.querySelector('[data-reference-status]').textContent.includes('reference.tbl의 기준정보 13개 시트를 열었습니다.'));
    check('Reference cell editing, .tbl and Excel export/import retain all 13 sheets');
    await page.screenshot({path:path.join(out,'reference.png')});
    await page.reload();await page.locator('.fp-editor').waitFor();await action('masterData').click();
    await page.getByRole('tab',{name:'랙타입 마스터',exact:true}).click();
    assert.match(await page.locator('[data-reference-grid]').innerText(),/로컬 기준정보 수정/);
    await action('drawing').click();
    await page.screenshot({path:path.join(out,'editor.png')});
    await page.setViewportSize({width:900,height:900});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.screenshot({path:path.join(out,'editor-compact.png')});
    check('Reload retains independent data; 900px viewport has no horizontal page overflow');
    const keys=await page.evaluate(()=>Object.keys(localStorage));
    assert.ok(keys.length>0&&keys.every(key=>key.startsWith('gics-standalone-')));
    assert.ok(requests.every(url=>url.startsWith(new URL('.',targetUrl).href)||url.startsWith('blob:')||url.startsWith('data:')));
    assert.deepEqual(errors,[]);
    check('No original storage keys, remote requests, missing assets or JavaScript errors');
    fs.writeFileSync(path.join(out,fileMode?'browser-checks.json':'server-browser-checks.json'),JSON.stringify({browser:'Microsoft Edge, headless, isolated test profile',url:targetUrl,offline:fileMode,checks,errors,keys,requests,limitations:['This automated run uses a picker test double. Native-window checks are separate; Korean IME composition was not exercised.']},null,2));
  } catch (error) {
    await page.screenshot({path:path.join(out,'failure.png')});
    console.error('Browser errors:',errors);
    console.error((await page.locator('body').innerText()).slice(-1800));
    throw error;
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
